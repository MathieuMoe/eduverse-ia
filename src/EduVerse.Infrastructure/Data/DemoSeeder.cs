        foreach (var (tutor, lessons) in new[] { ("Diego", 9), ("Grace", 6), ("Ahmed", 4), ("Claire", 3), ("Marc", 5), ("Inés", 4) })
        {
            var price = tutors.First(t => t.Name == tutor).Price;
            for (var i = 0; i < lessons; i++)
            {
                var start = Local(-3 - (i * 4) - random.Next(0, 3), 17 + random.Next(0, 3));
                var paidAt = start.AddDays(-2);
                var key = (tutor, paidAt.Month);
                var rate = Commission.Rate(gross.GetValueOrDefault(key));
                gross[key] = gross.GetValueOrDefault(key) + price;
                var rating = random.Next(0, 10) < 8 ? 5 : 4;
                db.Bookings.Add(new Booking
                {
                    TutorId = tutorIds[tutor],
                    StudentId = ids[students[(i + tutor.Length) % students.Length]],
                    Subject = tutors.First(t => t.Name == tutor).Subjects[0],
                    Start = start,
                    Price = price,
                    CommissionRate = rate,
                    Commission = Commission.Split(price, rate).Commission,
                    Status = BookingStatus.Completed,
                    PaymentReference = "SIM-SEED" + i.ToString(System.Globalization.CultureInfo.InvariantCulture),
                    Rating = rating,
                    Review = reviews[random.Next(reviews.Length)] is { Length: > 0 } r ? r : null,
                    CreatedAt = paidAt.AddMinutes(-5),
                    PaidAt = paidAt,
                });
            }
        }

        // Upcoming lessons with Diego (paid), one of them for the demo student Sara
        foreach (var (student, days, subject) in new[] { ("Sara", 3, "Fractions: adding with different denominators"), ("Iker", 5, "Simplifying fractions") })
        {
            var start = NextAvailable(Local(days, 18), tutors[0].Week, zone);
            db.Bookings.Add(new Booking
            {
                TutorId = tutorIds["Diego"],
                StudentId = ids[student],
                Subject = subject,
                Start = start,
                Price = 22m,
                CommissionRate = Commission.Standard,
                Commission = Commission.Split(22m, Commission.Standard).Commission,
                Status = BookingStatus.Confirmed,
                PaymentReference = "SIM-SEEDNEXT" + days.ToString(System.Globalization.CultureInfo.InvariantCulture),
                CreatedAt = now.AddDays(-1),
                PaidAt = now.AddDays(-1),
            });
        }

        await db.SaveChangesAsync(ct).ConfigureAwait(false);
    }

    /// <summary>The first day from <paramref name="from"/> on which the weekly availability has 18:00.</summary>
    private static DateTimeOffset NextAvailable(DateTimeOffset from, IReadOnlyList<WeeklySlot> week, TimeZoneInfo zone)
    {
        var start = from;
        for (var i = 0; i < 7 && !week.Any(w => w.Day == TimeZoneInfo.ConvertTime(start, zone).DayOfWeek && w.StartHour <= 18 && w.EndHour > 18); i++)
        {
            var local = TimeZoneInfo.ConvertTime(start, zone).DateTime.AddDays(1);
            start = new DateTimeOffset(local, zone.GetUtcOffset(local));
        }

        return start;
    }

    private static async Task<AppUser> CreateAsync(UserManager<AppUser> users, string email, string name, string role, DateTimeOffset now)
    {
        var user = new AppUser { UserName = email, Email = email, EmailConfirmed = true, DisplayName = name, IsDemo = true, CreatedAt = now };
        var result = await users.CreateAsync(user, Password).ConfigureAwait(false);
        if (!result.Succeeded)
        {
            throw new InvalidOperationException("Demo account not created: " + string.Join(", ", result.Errors.Select(e => e.Code)));
        }

        await users.AddToRoleAsync(user, role).ConfigureAwait(false);
        return user;
    }

    /// <summary>Replays answers through the mastery engine and writes states, attempts and alerts as the live app would.</summary>
    private sealed class Simulator(EduVerseDb db, DateTimeOffset now, Random random)
    {
        /// <param name="script">Steps separated by spaces: "C" = correct, "W" = wrong (any typical mistake), "W:Code" = wrong with that misconception.</param>
        public void Practice(string userId, string concept, int daysAgo, string script)
        {
            var state = MasteryState.New(concept);
            var at = now.AddDays(-daysAgo).AddHours(-2);
            foreach (var (correct, wanted) in Parse(script))
            {
                state = state.NeedsExplanation ? MasteryEngine.Explained(state) : state;
                var difficulty = MasteryEngine.NextDifficulty(state);
                var exercise = FractionExercises.Create(concept, difficulty, random, TeachLanguage.English);
                var choice = correct ? exercise.CorrectIndex : WrongChoice(exercise, wanted);
                var misconception = correct ? null : exercise.Misconceptions[choice];
                at = at.AddMinutes(3);
                db.Attempts.Add(new Attempt
                {
                    UserId = userId,
                    SubjectId = BuiltInSubjects.FractionsKey,
                    ConceptKey = concept,
                    ExerciseId = exercise.Id,
                    Question = exercise.Question,
                    Answer = exercise.Options[choice],
                    Correct = correct,
                    Misconception = misconception,
                    Method = state.Method,
                    Difficulty = difficulty,
                    At = at,
                });
                (state, var events) = MasteryEngine.Record(state, correct, difficulty, misconception, at);
                foreach (var e in events.Where(e => e.Kind is LearningEventKind.NeedsTeacher or LearningEventKind.RecurringMisconception))
                {
                    db.Alerts.Add(new Alert
                    {
                        StudentId = userId,
                        SubjectId = BuiltInSubjects.FractionsKey,
                        ConceptKey = concept,
                        Kind = e.Kind == LearningEventKind.NeedsTeacher ? AlertKind.NeedsTeacher : AlertKind.RecurringMisconception,
                        Detail = e.Detail,
                        CreatedAt = at,
                    });
                }
            }

            var record = new MasteryRecord { UserId = userId, SubjectId = BuiltInSubjects.FractionsKey, ConceptKey = concept };
            LearningStore.Copy(state, record);
            db.Mastery.Add(record);
        }

        private static int WrongChoice(Exercise exercise, string? wanted)
        {
            var index = wanted is null ? -1 : exercise.Misconceptions.ToList().IndexOf(wanted);
            return index >= 0 ? index : Enumerable.Range(0, exercise.Options.Count).First(i => i != exercise.CorrectIndex);
        }

        private static IEnumerable<(bool Correct, string? Code)> Parse(string script) =>
            script.Split(' ', StringSplitOptions.RemoveEmptyEntries).Select(t => (t == "C", t.StartsWith("W:", StringComparison.Ordinal) ? t[2..] : null));
    }
