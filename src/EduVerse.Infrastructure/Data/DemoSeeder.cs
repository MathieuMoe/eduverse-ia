            db.Mastery.Add(record);
        }

        await db.SaveChangesAsync(ct).ConfigureAwait(false);
    }

    private static async Task SeedGamificationAsync(EduVerseDb db, UserManager<AppUser> users, Dictionary<string, string> ids, TimeProvider clock, CancellationToken ct)
    {
        var now = clock.GetUtcNow();
        var mia = await CreateAsync(users, KidEmail, "Mia", Roles.Student, now.AddDays(-12)).ConfigureAwait(false);
        ids["Mia"] = mia.Id;
        db.StudentProfiles.Add(new StudentProfile { UserId = mia.Id, Language = TeachLanguage.English });
        await db.SaveChangesAsync(ct).ConfigureAwait(false);

        foreach (var (name, level, team) in new[] { ("Alex", Level.Primary3, Team.Foxes), ("Sara", Level.Primary3, Team.Owls), ("Leo", Level.Primary3, Team.Owls), ("Nora", Level.Primary3, Team.Dolphins), ("Mia", Level.EarlyYears, Team.Bears) })
        {
            var profile = await db.StudentProfiles.FirstAsync(p => p.UserId == ids[name], ct).ConfigureAwait(false);
            (profile.Level, profile.Stage, profile.Team) = (level, Levels.ToStage(level), team);
            (profile.Nickname, profile.Avatar) = Nicknames.Generate(GamificationStore.StableSeed(ids[name]), TeachLanguage.English);
        }

        // XP of the tutor history already seeded (fractions)
        var tutorAnswers = await db.Attempts.Where(a => !a.Diagnostic).ToListAsync(ct).ConfigureAwait(false);
        foreach (var a in tutorAnswers)
        {
            db.XpEvents.Add(new XpEvent { UserId = a.UserId, Amount = Xp.ForAnswer(a.Correct, a.Difficulty, 1), Reason = "tutor", Correct = a.Correct, At = a.At });
        }

        // Seeded tests fall on the local day they belong to, whatever the time of the seeding (streaks count local days)
        var zone = TimeZoneInfo.FindSystemTimeZoneById(new MarketplaceOptions().TimeZone);
        DateTimeOffset LocalAt(int daysAgo, int hour, int minutes)
        {
            var today = TimeZoneInfo.ConvertTime(now, zone).Date;
            var local = today.AddDays(-daysAgo).AddHours(hour);
            var at = new DateTimeOffset(local, zone.GetUtcOffset(local));
            if (at.AddMinutes(minutes) <= now)
            {
                return at;
            }

            var midnight = new DateTimeOffset(today, zone.GetUtcOffset(today));
            var early = now.AddMinutes(-minutes - 1);
            return early > midnight ? early : midnight;
        }

        var seed = 7000;
        void Test(string who, Area area, Level level, int daysAgo, string pattern, QuizMode mode = QuizMode.Practice, Level? placed = null, int? duelId = null)
        {
            var userId = ids[who];
            var start = LocalAt(daysAgo, 17 + daysAgo % 3, pattern.Length);
            var attempt = new QuizAttempt
            {
                Id = Guid.NewGuid().ToString("N"), UserId = userId, Area = area, Level = level, Mode = mode, Seed = seed++, Difficulty = 2,
                Length = pattern.Length, StartedAt = start, FinishedAt = start.AddMinutes(pattern.Length), Result = placed, DuelId = duelId, CurrentJson = "{}",
            };
            var run = 0;
            for (var i = 0; i < pattern.Length; i++)
            {
                var correct = pattern[i] == 'C';
                var question = QuestionBanks.Generate(area, level, 2, QuestionBanks.Seed(attempt.Seed, i, 2), TeachLanguage.English);
                var at = start.AddMinutes(i);
                run = correct ? run + 1 : 0;
                attempt.BestRun = Math.Max(attempt.BestRun, run);
                attempt.Correct += correct ? 1 : 0;
                db.QuizAnswers.Add(new QuizAnswer
                {
                    AttemptId = attempt.Id, UserId = userId, Area = area, Level = level, Topic = question.Topic, Difficulty = 2, Correct = correct, At = at,
                    Number = i + 1, Key = Quizzes.QuizStore.KeyOf(question), Prompt = question.Prompt, OptionsJson = JsonSerializer.Serialize(question.Options),
                    Choice = correct ? question.CorrectIndex : (question.CorrectIndex + 1) % 4, CorrectIndex = question.CorrectIndex,
                    Explanation = question.Explanation, Visual = question.Visual, Code = question.Code,
                });
                var xp = Xp.ForAnswer(correct, 2, run);
                attempt.Xp += xp;
                db.XpEvents.Add(new XpEvent { UserId = userId, Amount = xp, Reason = "answer", Correct = correct, At = at });
                var skill = db.TopicSkills.Local.FirstOrDefault(s => s.UserId == userId && s.Area == area && s.Level == level && s.Topic == question.Topic);
                if (skill is null)
                {
                    skill = new TopicSkill { UserId = userId, Area = area, Level = level, Topic = question.Topic, PKnown = BktParameters.DefaultPrior };
                    db.TopicSkills.Add(skill);
                }

                skill.PKnown = Bkt.Update(skill.PKnown, correct, BktParameters.ForDifficulty(2));
                skill.Attempts++;
                skill.Correct += correct ? 1 : 0;
                skill.LastAt = at;
                (skill.Box, skill.DueAt) = Spaced.Next(skill.Box, correct, 1, at);
            }

            var bonus = mode switch
            {
                QuizMode.Placement => Xp.PlacementFinished,
                QuizMode.Duel => 0,
                _ => Xp.TestFinished + (attempt.Correct == attempt.Length ? Xp.PerfectTest : 0),
            };
            if (bonus > 0)
            {
                db.XpEvents.Add(new XpEvent { UserId = userId, Amount = bonus, Reason = mode == QuizMode.Placement ? "placement" : "test", At = attempt.FinishedAt!.Value });
            }

            attempt.Xp += bonus;
            db.QuizAttempts.Add(attempt);
            if (db.SubjectLevels.Local.FirstOrDefault(s => s.UserId == userId && s.Area == area) is not { } record)
            {
                db.SubjectLevels.Add(new SubjectLevel { UserId = userId, Area = area, Level = placed ?? level, Placed = placed is not null, UpdatedAt = attempt.FinishedAt!.Value });
            }
            else if (placed is { } p)
            {
                (record.Level, record.Placed) = (p, true);
            }
        }

        // Sara: a week in a row, a perfect test, a placement test, physics still weak
        Test("Sara", Area.Mathematics, Level.Primary3, 9, "CCWCCCCWCC");
        Test("Sara", Area.Geography, Level.Primary3, 7, "CCCWCCCCWC");
        Test("Sara", Area.ForeignLanguage, Level.Primary3, 6, "CWCCWCCCWC");
        Test("Sara", Area.Mathematics, Level.Primary3, 5, "CCCCCCCCCC");
        Test("Sara", Area.Physics, Level.Primary3, 4, "CWWCCWCWWC");
        Test("Sara", Area.Geography, Level.Primary3, 3, "CCCCWCCCCC");
        Test("Sara", Area.History, Level.Primary2, 2, "CCCCWC", QuizMode.Placement, Level.Primary3);
        Test("Sara", Area.Biology, Level.Primary3, 1, "CCCCWCCCCC");

        // Classmates: Alex leads the week, Leo plays sometimes, Nora is new
        Test("Alex", Area.Mathematics, Level.Primary3, 0, "CCCCCCCCWC");
        Test("Alex", Area.Programming, Level.Primary3, 1, "CCCCCCCCCC");
        Test("Alex", Area.Physics, Level.Primary3, 2, "CCWCCCCCCC");
        Test("Alex", Area.Chemistry, Level.Primary3, 3, "CCCCWCCCCC");
        Test("Leo", Area.Mathematics, Level.Primary3, 1, "CWCCWCWCCC");
        Test("Leo", Area.Geography, Level.Primary3, 3, "CCWCCWCCCC");
        Test("Nora", Area.Language, Level.Primary3, 0, "CWCCWC");

        // Mia, 6 years old: counting and letters
        Test("Mia", Area.Mathematics, Level.EarlyYears, 2, "CCWCCCCCCC");
        Test("Mia", Area.Language, Level.EarlyYears, 1, "CCCCWCCCCC");

        // Duels: Sara beat Leo; Alex challenged Sara and is waiting for her
        var classroomId = await db.Classrooms.Where(c => c.Code == ClassCode).Select(c => c.Id).FirstAsync(ct).ConfigureAwait(false);
        var won = new Duel { ClassroomId = classroomId, ChallengerId = ids["Sara"], OpponentId = ids["Leo"], Area = Area.Geography, Level = Level.Primary3, Seed = 4242, ChallengerScore = 4, OpponentScore = 3, Status = DuelStatus.Finished, CreatedAt = now.AddDays(-5), FinishedAt = now.AddDays(-4) };
        var waiting = new Duel { ClassroomId = classroomId, ChallengerId = ids["Alex"], OpponentId = ids["Sara"], Area = Area.Mathematics, Level = Level.Primary3, Seed = 5151, ChallengerScore = 4, Status = DuelStatus.Waiting, CreatedAt = now.AddHours(-20) };
        db.Duels.AddRange(won, waiting);
        await db.SaveChangesAsync(ct).ConfigureAwait(false);
        Test("Sara", Area.Geography, Level.Primary3, 5, "CCWCC", QuizMode.Duel, duelId: won.Id);
        Test("Leo", Area.Geography, Level.Primary3, 4, "CWCCW", QuizMode.Duel, duelId: won.Id);
        Test("Alex", Area.Mathematics, Level.Primary3, 1, "CCCWC", QuizMode.Duel, duelId: waiting.Id);
        db.XpEvents.Add(new XpEvent { UserId = ids["Sara"], Amount = Xp.DuelWin, Reason = "duel", At = won.FinishedAt!.Value });
        await db.SaveChangesAsync(ct).ConfigureAwait(false);

        // Badges and today's quests, by the real rules
        var game = new GamificationStore(db, clock, Microsoft.Extensions.Options.Options.Create(new MarketplaceOptions()));
        foreach (var name in new[] { "Alex", "Sara", "Leo", "Nora", "Mia" })
        {
            await game.CheckAsync(ids[name], ct).ConfigureAwait(false);
        }
    }

