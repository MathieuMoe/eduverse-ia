    public static async Task SeedAsync(EduVerseDb db, UserManager<AppUser> users, RoleManager<IdentityRole> roles, TimeProvider clock, CancellationToken ct = default)
    {
        ArgumentNullException.ThrowIfNull(db);
        ArgumentNullException.ThrowIfNull(users);
        ArgumentNullException.ThrowIfNull(roles);
        ArgumentNullException.ThrowIfNull(clock);
        foreach (var role in Roles.All)
        {
            if (!await roles.RoleExistsAsync(role).ConfigureAwait(false))
            {
                await roles.CreateAsync(new IdentityRole(role)).ConfigureAwait(false);
            }
        }

        if (await users.FindByEmailAsync(TeacherEmail).ConfigureAwait(false) is not null)
        {
            return; // already seeded
        }

        var now = clock.GetUtcNow();
        var teacher = await CreateAsync(users, TeacherEmail, "Laura", Roles.Teacher, now).ConfigureAwait(false);
        var classroom = new Classroom { Name = "Maths 2B", Code = ClassCode, TeacherId = teacher.Id, SubjectId = BuiltInSubjects.FractionsKey, CreatedAt = now.AddDays(-30) };
        db.Classrooms.Add(classroom);

        var ids = new Dictionary<string, string>();
        foreach (var (email, name) in Students)
        {
            var user = await CreateAsync(users, email, name, Roles.Student, now).ConfigureAwait(false);
            ids[name] = user.Id;
            db.StudentProfiles.Add(new StudentProfile { UserId = user.Id, Stage = Stage.Secondary, Language = TeachLanguage.English });
            classroom.Members.Add(new ClassMember { UserId = user.Id, JoinedAt = now.AddDays(-28) });
        }

        await db.SaveChangesAsync(ct).ConfigureAwait(false);

        var sim = new Simulator(db, now, new Random(2024));

        // Alex: masters six concepts; "meaning" was mastered 10 days ago, so a spaced review is due
        sim.Practice(ids["Alex"], "meaning", 10, "C C C C C");
        sim.Practice(ids["Alex"], "equivalent", 9, "C W C C C C");
        sim.Practice(ids["Alex"], "simplify", 6, "C C C C C");
        sim.Practice(ids["Alex"], "compare", 5, "C C W C C C C");
        sim.Practice(ids["Alex"], "add-same", 4, "C C C C C");
        sim.Practice(ids["Alex"], "add-different", 2, "C C W C C C C");
        sim.Practice(ids["Alex"], "multiply", 1, "C W C");

        // Sara: adds the denominators again and again when they are different
        sim.Practice(ids["Sara"], "meaning", 6, "C C C C C");
        sim.Practice(ids["Sara"], "equivalent", 5, "C C C C C C");
        sim.Practice(ids["Sara"], "simplify", 5, "C C W C C C C");
        sim.Practice(ids["Sara"], "compare", 4, "C W:BiggerDenominatorBigger C C C C");
        sim.Practice(ids["Sara"], "add-same", 3, "C C C C C");
        sim.Practice(ids["Sara"], "add-different", 1, "W:AddAcross C W:AddAcross W:NotConverted C");

        // Leo: comparing fractions resists three explanation methods, the tutor asks for the teacher
        sim.Practice(ids["Leo"], "meaning", 9, "C C W C C C");
        sim.Practice(ids["Leo"], "equivalent", 7, "C C C W C");
        sim.Practice(ids["Leo"], "compare", 2, "W:BiggerDenominatorBigger W:SameNumeratorEqual W:BiggerDenominatorBigger C W:BiggerDenominatorBigger W:SameNumeratorEqual W:BiggerDenominatorBigger");

        // Nora: just joined, no history yet (her first step is the placement test)
        await db.SaveChangesAsync(ct).ConfigureAwait(false);

        await SeedInstitutionAsync(db, users, sim, teacher, ids, now, ct).ConfigureAwait(false);
        await SeedMarketplaceAsync(db, users, ids, now, ct).ConfigureAwait(false);
